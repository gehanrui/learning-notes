import numpy as np

print("=" * 58)
print(" 第 2 章：矩阵运算")
print("=" * 58)

A = np.array([[1, 2],
              [3, 4]])
B = np.array([[5, 6],
              [7, 8]])
print("A =", A.tolist())
print("B =", B.tolist())

# ---- 矩阵加法 ----
print("\n【1】矩阵加法：对应位置相加")
print("A + B =", (A + B).tolist())
print("→ 手算：1+5=6, 2+6=8, 3+7=10, 4+8=12")

# ---- 矩阵乘法（重点） ----
print("\n【2】矩阵乘法 A @ B   ★本章核心")
print("A @ B =", (A @ B).tolist())
print()
print("手算规则：第 i 行 点乘 第 j 列")
print("  (1,1): 1*5 + 2*7 =", 1*5 + 2*7)
print("  (1,2): 1*6 + 2*8 =", 1*6 + 2*8)
print("  (2,1): 3*5 + 4*7 =", 3*5 + 4*7)
print("  (2,2): 3*6 + 4*8 =", 3*6 + 4*8)

# ---- 不满足交换律 ----
print("\n【3】★ 矩阵乘法不满足交换律（最容易错的地方）")
print("A @ B =", (A @ B).tolist())
print("B @ A =", (B @ A).tolist())
print("→ 两者不同！普通乘法 3×4 = 4×3，但矩阵不行")

# ---- 转置 ----
print("\n【4】转置 A.T：行变列、列变行")
print("A     =", A.tolist())
print("A.T   =", A.T.tolist())
print("→ 在 EEG 里：原始数据可能是 通道×时间点，转置后变成 时间点×通道")

